json_llm_report::json_llm_report()
    : m_pimpl(std::make_unique<json_llm_report_impl>()) {}

json_llm_report::~json_llm_report() = default;

void json_llm_report::write(cfg_ref_t cfg, const AnalysisParams &params,
                            const abs_dom_map_t &invariants,
                            const abs_dom_map_t &post_invariants,
                            const checks_db_t &checks, const voi_map_t &voi) {
  m_pimpl->write(cfg, params, invariants, post_invariants, checks, voi);
}

std::string json_llm_report::generate() { return m_pimpl->generate(); }

